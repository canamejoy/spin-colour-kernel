"""Build a self-contained Kaggle script kernel: the package travels base64-embedded, no repository access.

    python remote/make_kaggle.py --slug sck-poc-a --user <kaggle user> --exp E1,E2,E3,E5 --out build/kaggle/a
"""

import argparse
import base64
import io
import json
import subprocess
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

TEMPLATE = r'''# Generated by remote/make_kaggle.py -- spin-colour-kernel @ {commit}
import base64, io, os, subprocess, sys, tarfile, time
os.environ.setdefault("XLA_PYTHON_CLIENT_PREALLOCATE", "false")
W = "/kaggle/working"
SRC = os.path.join(W, "sck_src")
tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz").extractall(SRC)
print("commit {commit}", flush=True)
subprocess.run(["nvidia-smi"])
for mod in ("torch", "triton", "jax", "scipy"):
    try:
        m = __import__(mod); print(mod, m.__version__, flush=True)
    except Exception as e:
        print(mod, "missing", e, flush=True)
try:
    import scipy  # noqa
except Exception:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "scipy"])
trees = [("", SRC)]
if AB_BUNDLE:                      # A/B on one machine: the baseline tree and this one, alternated
    OLD = os.path.join(W, "sck_src_ab")
    tarfile.open(fileobj=io.BytesIO(base64.b64decode(AB_BUNDLE)), mode="r:gz").extractall(OLD)
    trees = [(f"ab-{{AB_COMMIT}}-r{{k}}", OLD) if i == 0 else (f"head-r{{k}}", SRC)
             for k in range({rounds}) for i in (0, 1)]
for tag, tree in trees:
    env = dict(os.environ, PYTHONPATH=tree, SCK_CACHE=os.path.join(W, "sck_cache", tag or "x"))
    t0 = time.time()
    r = subprocess.run([sys.executable, "-m", "Spin_Colour_Kernel.run", "--exp", "{exp}", "--out",
                        os.path.join(W, "results", tag), "--device", "cuda:0"] + {extra}, env=env, cwd=W)
    print("runner", tag or "main", "exit", r.returncode, "elapsed", time.time() - t0, flush=True)
subprocess.run(["rm", "-rf", SRC, os.path.join(W, "sck_src_ab"), os.path.join(W, "sck_cache"), "/tmp/sck"])
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--slug", required=True)
    ap.add_argument("--user", required=True)
    ap.add_argument("--exp", required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--title", default=None)
    ap.add_argument("--ab", default=None, help="baseline commit: run --exp with it and with HEAD, alternated")
    ap.add_argument("--rounds", type=int, default=2)
    a = ap.parse_args()
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as t:
        t.add(ROOT / "src" / "Spin_Colour_Kernel", arcname="Spin_Colour_Kernel",
              filter=lambda ti: None if "__pycache__" in ti.name else ti)
    commit = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"], capture_output=True,
                            text=True).stdout.strip() or "uncommitted"
    a.out.mkdir(parents=True, exist_ok=True)
    body = TEMPLATE.format(commit=commit, exp=a.exp, extra=repr(["--smoke"] if a.smoke else []), rounds=a.rounds)
    ab = ""
    if a.ab:
        import shutil
        import tempfile
        tmp = Path(tempfile.mkdtemp())
        arc = subprocess.run(["git", "-C", str(ROOT), "archive", a.ab, "src/Spin_Colour_Kernel"], capture_output=True,
                             check=True).stdout
        tarfile.open(fileobj=io.BytesIO(arc)).extractall(tmp)
        b2 = io.BytesIO()
        with tarfile.open(fileobj=b2, mode="w:gz") as t:
            t.add(tmp / "src" / "Spin_Colour_Kernel", arcname="Spin_Colour_Kernel")
        shutil.rmtree(tmp)
        ab = base64.b64encode(b2.getvalue()).decode()
    code = ("BUNDLE = " + repr(base64.b64encode(buf.getvalue()).decode()) + "\n" + "AB_BUNDLE = " + repr(ab)
            + "\n" + "AB_COMMIT = " + repr(a.ab or "") + "\n" + body)
    (a.out / "run.py").write_text(code)
    meta = {"id": f"{a.user}/{a.slug}", "title": a.title or a.slug, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
            "machine_shape": "NvidiaTeslaT4", "dataset_sources": [], "competition_sources": [],
            "kernel_sources": []}
    (a.out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print(a.out, len(code), "bytes", commit)


if __name__ == "__main__":
    main()
